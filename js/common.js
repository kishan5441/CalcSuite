// THEME MANAGEMENT

function initTheme() {

    const saved = localStorage.getItem("calcsuite-theme");

    if (saved === "light") {
        document.body.classList.add("light");
    }

    const button = document.getElementById("themeToggle");

    if (button) {

        button.addEventListener("click", () => {

            document.body.classList.toggle("light");

            const theme = document.body.classList.contains("light")
                ? "light"
                : "dark";

            localStorage.setItem("calcsuite-theme", theme);

        });

    }

}


// GET NUMBER INPUT

function getNumber(id) {

    const value = Number(document.getElementById(id).value);

    return Number.isFinite(value) ? value : 0;

}


// CURRENCY FORMAT

function formatMoney(amount, currency = "INR") {

    return new Intl.NumberFormat("en-IN", {

        style: "currency",
        currency: currency,
        maximumFractionDigits: 0

    }).format(Number(amount) || 0);

}


// CSV EXPORT

function exportCSV(filename, rows) {

    const csv = rows.map(row => {

        return row.map(value => {

            return `"${String(value ?? "").replace(/"/g, '""')}"`;

        }).join(",");

    }).join("\r\n");

    const blob = new Blob(
        ["\uFEFF" + csv],
        { type: "text/csv;charset=utf-8;" }
    );

    const url = URL.createObjectURL(blob);

    const link = document.createElement("a");

    link.href = url;
    link.download = filename;

    document.body.appendChild(link);

    link.click();

    link.remove();

    URL.revokeObjectURL(url);

}


// PDF EXPORT

function exportPDF(filename, title, summary, headers, rows) {

    if (!window.jspdf) {

        alert("PDF library not loaded. Check internet connection.");

        return;

    }

    const { jsPDF } = window.jspdf;

    const doc = new jsPDF("landscape");

    doc.setFontSize(19);

    doc.text(title, 14, 18);

    doc.setFontSize(9);

    doc.text(
        "Generated by CalcSuite | " + new Date().toLocaleString(),
        14,
        25
    );

    let y = 36;

    summary.forEach(item => {

        doc.text(item[0] + ": " + item[1], 14, y);

        y += 7;

    });

    const body = rows.map(row => row.map(String));

    if (typeof doc.autoTable === "function") {

        doc.autoTable({

            head: [headers],

            body: body,

            startY: y + 5,

            theme: "grid",

            styles: {
                fontSize: 8,
                cellPadding: 3
            },

            headStyles: {
                fillColor: [105, 87, 220]
            }

        });

    } else {

        doc.setFontSize(8);

        body.forEach(row => {

            y += 6;

            if (y > 185) {

                doc.addPage();

                y = 15;

            }

            doc.text(row.join(" | ").substring(0, 160), 14, y);

        });

    }

    doc.save(filename);

}


